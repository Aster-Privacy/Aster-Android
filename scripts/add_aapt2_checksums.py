import hashlib
import re
import sys
import urllib.request

OPERATING_SYSTEMS = ("linux", "osx", "windows")


def fetch_sha256(url):
    with urllib.request.urlopen(url, timeout=120) as response:
        return hashlib.sha256(response.read()).hexdigest()


def artifact_block(name, digest):
    return (
        f'         <artifact name="{name}">\n'
        f'            <sha256 value="{digest}" origin="Generated by Gradle"/>\n'
        f"         </artifact>\n"
    )


def main():
    metadata_path, version, base_url = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(metadata_path, encoding="utf-8") as handle:
        text = handle.read()

    opening = f'      <component group="com.android.tools.build" name="aapt2" version="{version}">\n'
    if opening not in text:
        anchor = "   </components>\n"
        if anchor not in text:
            raise SystemExit("components section not found")
        text = text.replace(anchor, opening + "      </component>\n" + anchor, 1)

    start = text.index(opening) + len(opening)
    end = text.index("      </component>\n", start)
    component = text[start:end]

    for operating_system in OPERATING_SYSTEMS:
        name = f"aapt2-{version}-{operating_system}.jar"
        digest = fetch_sha256(f"{base_url}/{name}")
        existing = re.search(
            rf'<artifact name="{re.escape(name)}">\s*<sha256 value="([0-9a-f]+)"', component
        )
        if existing:
            if existing.group(1) != digest:
                raise SystemExit(f"checksum mismatch for {name}")
            continue
        component += artifact_block(name, digest)

    text = text[:start] + component + text[end:]
    with open(metadata_path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


if __name__ == "__main__":
    main()
